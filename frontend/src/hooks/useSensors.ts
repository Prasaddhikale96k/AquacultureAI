import { useCallback, useEffect, useRef, useState } from "react";
import { CONFIG, SENSOR_KEYS, configProblem, fetchReadings, type Mapping, type Reading } from "../services/thingspeak";
import { LABELS, UNITS } from "../config/alerts";

export interface Activity { t: number; text: string; tone: "info" | "warn" }

/** Polls ThingSpeak (read-only). One request at a time; a stale/failed request never overwrites a newer success. */
export function useSensors() {
  const problem = configProblem();
  const [readings, setReadings] = useState<Reading | null>(null);
  const [mapping, setMapping] = useState<Mapping | null>(null);
  const [rejected, setRejected] = useState(0);
  const [error, setError] = useState<string | null>(null);   // last refresh failed: previous readings are kept but marked stale
  const [fetchedAt, setFetchedAt] = useState<number | null>(null);
  const [busy, setBusy] = useState(false);
  const [activity, setActivity] = useState<Activity[]>([]);   // events generated by this app, newest first
  const ctl = useRef<AbortController | null>(null);
  const seq = useRef(0);
  const lastEntry = useRef<number | null>(null);
  const lastError = useRef<string | null>(null);
  const log = useCallback((text: string, tone: Activity["tone"] = "info") => setActivity((a) => [{ t: Date.now(), text, tone }, ...a].slice(0, 20)), []);

  const refresh = useCallback(async () => {
    if (problem || ctl.current) return;                       // not configured, or a request is already in flight
    const mine = ++seq.current;
    const c = (ctl.current = new AbortController());
    setBusy(true);
    try {
      const r = await fetchReadings(c.signal);
      if (mine !== seq.current) return;
      setReadings(r.readings); setMapping(r.mapping); setRejected(r.rejected); setError(null); setFetchedAt(Date.now());
      if (lastError.current) { log("ThingSpeak fetch recovered."); lastError.current = null; }
      const ids = SENSOR_KEYS.flatMap((k) => r.readings[k].map((p) => p.id ?? 0));
      const newest = ids.length ? Math.max(...ids) : 0;
      if (newest > 0) {
        if (lastEntry.current === null) log(`Connected: loaded ${SENSOR_KEYS.reduce((n, k) => Math.max(n, r.readings[k].length), 0)} recent readings (latest entry #${newest}).`);
        else if (newest > lastEntry.current) {
          const parts = SENSOR_KEYS.flatMap((k) => { const p = r.readings[k].find((x) => x.id === newest); return p ? [`${LABELS[k]} ${p.v} ${UNITS[k]}`] : []; });
          log(`New data received (entry #${newest})${parts.length ? ` — ${parts.join(" · ")}.` : "."}`);
        }
        lastEntry.current = Math.max(lastEntry.current ?? 0, newest);
      }
    } catch (e) {
      if ((e as Error).name === "AbortError" || mine !== seq.current) return;
      const msg = (e as Error).message;
      setError(msg);
      if (msg !== lastError.current) { log(`ThingSpeak fetch failed: ${msg}`, "warn"); lastError.current = msg; }
    } finally { if (ctl.current === c) ctl.current = null; setBusy(false); }
  }, [problem, log]);

  useEffect(() => {
    if (problem) return;
    void refresh();
    const id = window.setInterval(() => { if (!document.hidden) void refresh(); }, CONFIG.pollMs);
    return () => { window.clearInterval(id); seq.current++; ctl.current?.abort(); ctl.current = null; };
  }, [refresh, problem]);

  return { problem, readings, mapping, rejected, error, fetchedAt, busy, activity, refresh, staleMs: CONFIG.staleMs, pollMs: CONFIG.pollMs };
}
export type Sensors = ReturnType<typeof useSensors>;
